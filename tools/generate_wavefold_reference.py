#!/usr/bin/env python3
"""Generate static high-precision ADAA2 near-corner vectors (stdlib only)."""
from decimal import Decimal as D, getcontext, ROUND_FLOOR
import random
getcontext().prec = 80

def f2(x, gain):
    u=x*gain; au=abs(u)
    if au>=8: h=D(4)
    else:
        m=(au/2).to_integral_value(rounding=ROUND_FLOOR); s=au-2*m
        b=s**3/6 if s<=1 else s*s-s**3/6-s+D(1)/3
        h=m+s-b if int(m)%2 else m+b
    return (-h if u<0 else h)/(gain*gain)

def f1(x, gain):
    u=x*gain; au=abs(u)
    if au>=8: return D(0)
    m=(au/2).to_integral_value(rounding=ROUND_FLOOR); s=au-2*m
    a=s*s/2 if s<=1 else 2*s-s*s/2-1
    return (1-a if int(m)%2 else a)/gain

def value(x, gain):
    u=x*gain; au=abs(u)
    if au>=8:return D(0)
    m=(au/2).to_integral_value(rounding=ROUND_FLOOR); s=au-2*m
    v=s if s<=1 else 2-s
    return -v if bool(int(m)%2) != (u<0) else v

def divided(a,b,g): return f1(a,g) if a==b else (f2(a,g)-f2(b,g))/(a-b)
def reference(a,b,c,g):
    if a==b==c:return value(a,g)
    if a==c:return 2*(f1(a,g)-divided(a,b,g))/(a-b)
    return 2*(divided(a,b,g)-divided(b,c,g))/(a-c)

print('// Generated by tools/generate_wavefold_reference.py; 80-digit Decimal.')
print('inline constexpr WavefoldReference wavefoldReferences[] = {')
for gain in (1.0,2.0,8.0):
    for corner in (-8.0,-2.0,-1.0,1.0,2.0,8.0):
        for step in (1e-9,1e-6,1e-5):
            for mode in (0,1,2,3):
                centre=corner/gain
                a,b=centre+step,centre-step
                c=centre if mode==0 else a if mode==1 else b
                if mode==2:
                    b=a
                g,x0,x1,x2=map(D.from_float,(gain,a,b,c))
                expected=float(reference(x0,x1,x2,g))
                print('    { '+', '.join(format(x,'.17g') for x in (gain,a,b,c,expected))+' },')
rng=random.Random(1197)
for i in range(96):
    gain=rng.uniform(1.0,8.0)
    b=rng.uniform(-1.0,1.0)
    a=b+rng.uniform(-1e-5,1e-5)
    c=a+rng.uniform(-1e-5,1e-5) if i%3==0 else rng.uniform(-1.0,1.0)
    g,x0,x1,x2=map(D.from_float,(gain,a,b,c))
    expected=float(reference(x0,x1,x2,g))
    print('    { '+', '.join(format(x,'.17g') for x in (gain,a,b,c,expected))+' },')
print('};')
