#pragma once
// Publisher trust for native .vins packages (#73/#77). SHA-256 member hashes
// only show integrity; authenticity comes from an RSA-PKCS#1 v1.5 SHA-256
// signature over the exact manifest bytes, verified against publisher public
// keys pinned into this Rack build at compile time. Only verification lives
// here; private keys never enter the Rack, the repository or build logs.
#include <cstdint>
#include <span>
#include <string>
#include <vector>

namespace vstengine::instrument::vins {

struct PublisherKey {
  std::string id;                      // 16 hex digits of SHA-256(modulus)
  std::string label;                   // e.g. "Ultima Vox release" / "CI ephemeral"
  std::vector<std::uint8_t> modulus;   // big-endian, no leading zero byte
  std::uint32_t exponent{65537};
};

// Smallest accepted modulus (bits). Shorter keys are not trusted.
inline constexpr std::size_t minPublisherKeyBits = 3072;

// "Modulus=HEX" or plain hex as printed by `openssl rsa -modulus`.
[[nodiscard]] bool parseModulusHex(const std::string &text, std::vector<std::uint8_t> &out);

// Key id for a big-endian modulus.
[[nodiscard]] std::string publisherKeyId(std::span<const std::uint8_t> modulus);

// True when `signature` is a valid RSASSA-PKCS1-v1_5 SHA-256 signature of
// `message` under `key`. The full encoded block is rebuilt and compared byte
// for byte; nothing in the signed block is parsed.
[[nodiscard]] bool verifySignature(const PublisherKey &key, std::span<const std::uint8_t> message,
                                   std::span<const std::uint8_t> signature);

// Publisher keys pinned into this build (generated by CMake; may be empty,
// in which case no native package is trusted).
[[nodiscard]] const std::vector<PublisherKey> &pinnedPublisherKeys();

} // namespace vstengine::instrument::vins
